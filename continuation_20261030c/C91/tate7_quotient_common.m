SetColumns(0); SetQuitOnError(true); SetNthreads(1); SetMemoryLimit(12*10^9); tt:=Cputime();
F:=GF(2); FB<t>:=FunctionField(F);
b7:=t^3-t^2; c7:=t^2-t;
Eu:=EllipticCurve([1-c7,-b7,-b7,FB!0,FB!0]); Pu:=Eu![0,0]; assert Order(Pu) eq 7;
ju:=jInvariant(Eu);
FX<X>:=FunctionField(FB);
j13:=(X^2+5*X+13)*(X^4+7*X^3+20*X^2+19*X+1)^3/X;
f:=Numerator(j13-ju); assert Degree(f) eq 14 and IsIrreducible(f);
CY<s>:=FunctionField(f); jt:=CY!ju;
assert Genus(CY) eq 23;
tau:=hom<CY->CY|hom<FB->CY|1/((CY!t)+1)>,s>;
assert tau(tau(tau(CY!t))) eq CY!t and tau(tau(tau(s))) eq s and tau(jt) eq jt;
printf "C91_TATE7_QUOTIENT_READY genus23=true degree14=true deck3=true time=%o\n",Cputime(tt);
cys:=Poles(jt); widths:=[-Valuation(jt,P):P in cys];
assert {*<widths[i],Degree(cys[i])>:i in [1..#cys]*} eq {*<91,1>^^3,<13,3>^^1,<7,1>^^3,<1,3>^^1*};
cs:=[cys[i]:i in [1..#cys]|widths[i] in [91,13]];
assert {*Degree(P):P in cs*} eq {*1^^3,3^^1*};
printf "C91_TATE7_CUSPS_READY signature=%o time=%o\n",[<widths[i],Degree(cys[i])>:i in [1..#cys]],Cputime(tt);
Omega,om:=SpaceOfHolomorphicDifferentials(CY); B:=[om(v):v in Basis(Omega)];
CM:=Matrix(F,[Eltseq(Cartier(w)@@om):w in B]);
eta:=Differential(CY!FB.1); hs:=[w/eta:w in B];
MT:=Matrix(F,[Eltseq((tau(q)*Differential(tau(CY!FB.1)))@@om):q in hs]); I23:=IdentityMatrix(F,23);
assert MT^3 eq I23 and MT*CM eq CM*MT;
U:=RowSpace((CM-I23)*(MT-I23));
printf "C91_TATE7_DIFFERENTIALS_READY CartierRank=%o tauMinusRank=%o Udim=%o time=%o\n",Rank(CM),Rank(MT-I23),Dimension(U),Cputime(tt);
